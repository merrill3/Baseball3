// Builds js/core/realnames.js: a hash of every real MLB player's name that B3.names could build (DESIGN.md section 6, the
// names rule; M2 step 2.1a task 2, Session 27, Claude's default). Node only.
// Usage: node tools/realnames.js DIR
//   DIR holds the Chadwick Bureau register's people files (people-0.csv ... people-f.csv), downloaded from
//   https://github.com/chadwickbureau/register (data/), Open Data Commons Attribution License.
// It keeps everyone with an MLB season (mlb_played_first), 1871 on. A player's name counts under his used first name, his
// given first name, his whole given name and his nickname, each with his last name (accents and anything but letters
// dropped, as B3.names.key does). Only names whose first and last part are both in B3.names' lists can come out of the
// generator, so only those are kept, as hashes: no real names are written into the repo.
'use strict';
const fs = require('fs');
const path = require('path');
const { loadCore, ROOT } = require('./lib/load');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; } else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function main() {
  const dir = process.argv[2];
  if (!dir) { console.error('usage: node tools/realnames.js DIR (the register\'s people-*.csv files)'); process.exit(1); }
  const B3 = loadCore();
  const N = B3.names;
  const firsts = new Set(), lasts = new Set();
  for (const g in N.FIRST) for (const x of N.FIRST[g]) firsts.add(N.norm(x));
  for (const g in N.LAST) for (const x of N.LAST[g]) lasts.add(N.norm(x));
  const files = fs.readdirSync(dir).filter((f) => /^people-[0-9a-f]\.csv$/.test(f)).sort();
  if (files.length !== 16) { console.error('expected 16 people-?.csv files in ' + dir + ', found ' + files.length); process.exit(1); }
  let players = 0;
  const kept = new Set();
  for (const f of files) {
    const rows = parseCsv(fs.readFileSync(path.join(dir, f), 'utf8'));
    const head = rows[0], col = (k) => head.indexOf(k);
    const iLast = col('name_last'), iFirst = col('name_first'), iGiven = col('name_given'), iNick = col('name_nick'), iMlb = col('mlb_played_first');
    if ([iLast, iFirst, iGiven, iNick, iMlb].some((i) => i < 0)) { console.error(f + ': missing columns'); process.exit(1); }
    for (let r = 1; r < rows.length; r++) {
      const row = rows[r];
      if (!row[iMlb]) continue;
      players++;
      const last = N.norm(row[iLast] || '');
      if (!lasts.has(last)) continue;
      const given = (row[iGiven] || '').trim();
      for (const fn of [row[iFirst], given.split(/\s+/)[0], given, row[iNick]]) {
        const first = N.norm(fn || '');
        if (first && firsts.has(first)) kept.add(N.hash(first + ' ' + last));
      }
    }
  }
  const hashes = Array.from(kept).sort();
  const out = '// Generated by `node tools/realnames.js DIR` (' + new Date().toISOString().slice(0, 10) + '): do not edit by hand. No player names:\n' +
    '// hashes (B3.names.hash of B3.names.key) of the ' + hashes.length + ' real MLB player names, from the ' + players + ' players with an MLB\n' +
    '// season in the Chadwick Bureau register (github.com/chadwickbureau/register, ODC Attribution License), whose first and\n' +
    '// last name are both in B3.names\' lists. B3.names.pick draws again on any of them. Rebuild it after changing the lists.\n' +
    '(function (root) {\n  \'use strict\';\n  const B3 = root.B3 = root.B3 || {};\n  B3.realNames = {\n    players: ' + players + ',\n    count: ' + hashes.length + ',\n' +
    '    hashes: \'' + wrap(hashes.join(',')) + '\'\n  };\n})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';
  fs.writeFileSync(path.join(ROOT, 'js', 'core', 'realnames.js'), out);
  console.log(players + ' MLB players; ' + hashes.length + ' names buildable from the lists; wrote js/core/realnames.js (' + out.length + ' bytes)');
}

// Long lines in pieces of about 110 characters, joined by the code as one string.
function wrap(text) {
  const parts = [];
  for (let i = 0; i < text.length;) {
    let j = Math.min(text.length, i + 110);
    while (j < text.length && text[j - 1] !== ',') j++;
    parts.push(text.slice(i, j)); i = j;
  }
  return parts.join('\' +\n      \'');
}

main();
